/// The window as Slint generates it. That code is not ours to hold to our lints, so they stop at
/// this module, and everything else is held to all of them.
#[allow(clippy::all, clippy::pedantic, clippy::nursery, clippy::restriction, reason = "code generated by Slint")]
mod ui {
    slint::include_modules!();
}
pub use ui::*;

#[global_allocator]
static ALLOCATOR: mimalloc::MiMalloc = mimalloc::MiMalloc;

const WORKERS: usize = 2;
const COMMIT_SHOWN: usize = 8;
/// Where the window's own buttons end, on systems that draw them inside the window.
const BUTTONS_INSET: f32 = if cfg!(target_os = "macos") { 84.0 } else { 12.0 };
const WIDTH: f32 = 1280.0;
const HEIGHT: f32 = 820.0;

/// The window's own buttons sit over the sidebar, with no title bar across the top. The toolkit's
/// default menu goes: it would take the menu bar back each time a window gets focus.
fn pick_backend() -> Result<(), Box<dyn std::error::Error>> {
    let builder = i_slint_backend_winit::Backend::builder()
        .with_renderer_name("software")
        .with_custom_application_handler(Box::<shortcuts::AnyLayout>::default());
    #[cfg(target_os = "macos")]
    let builder = builder.with_default_menu_bar(false).with_window_attributes_hook(|attributes| {
        use slint::winit_030::winit::platform::macos::WindowAttributesExtMacOS;
        attributes.with_title_hidden(true).with_titlebar_transparent(true).with_fullsize_content_view(true)
    });
    slint::platform::set_platform(Box::new(builder.build()?))?;
    Ok(())
}

/// What the window shows of itself before anything is signed in.
fn dress(app: &App) {
    if !window_place::restore_size(app) {
        app.window().set_size(slint::LogicalSize::new(WIDTH, HEIGHT));
    }
    app.set_buttons_inset(BUTTONS_INSET);
    let commit = env!("BUILD_COMMIT");
    app.set_version_text(format!("v{}", env!("CARGO_PKG_VERSION")).into());
    app.set_commit_text(commit.chars().take(COMMIT_SHOWN).collect::<String>().into());
    app.set_commit_link(format!("{REPOSITORY}/tree/{commit}").into());
}

/// The mailbox lives in the core, and every change of it is drawn here.
fn follow_the_view(service: &Arc<Service>, app: &App) {
    let (views, weak) = (Arc::downgrade(service), app.as_weak());
    service.on_view(Box::new(move |update| {
        if let Some(service) = views.upgrade() {
            publish(&service, &weak, update);
        }
    }));
    let weak = app.as_weak();
    service.on_stage(Box::new(move |stage| show_stage(&weak, stage)));
}

fn connect_mail(service: &Arc<Service>, app: &App) {
    let (folders, weak) = (service.clone(), app.as_weak());
    app.on_open_folder(move |id| {
        let (service, id, weak) = (folders.clone(), id.to_string(), weak.clone());
        log::info!("opening {}", view::folder_for_the_journal(&id));
        list_title(&weak, &id);
        mail_view::close();
        tokio::spawn(async move { service.view_open(&id).await });
    });
    let (mails, weak) = (service.clone(), app.as_weak());
    app.on_open_mail(move |id| open_mail(&mails, &weak, id.to_string()));
    let (closing, weak) = (service.clone(), app.as_weak());
    app.on_close_mail(move || close_mail(&closing, &weak));
    let (stepping, weak) = (service.clone(), app.as_weak());
    app.on_step(move |delta| view::step(&stepping, &weak, delta));
    app.on_info_requested(open_info);
}

/// The window's own: its close button, the menus that are the system's, and the More button.
fn connect_window(service: &Arc<Service>, app: &App) {
    let weak = app.as_weak();
    app.on_more_requested(move || {
        if let Some(app) = weak.upgrade() {
            tray::show_more(&app);
        }
    });
    tray::listen(app);
    // Closing the window leaves the app in the tray, and its webview goes with the window.
    let (closing, weak) = (service.clone(), app.as_weak());
    app.window().on_close_requested(move || {
        if let Some(app) = weak.upgrade() {
            window_place::remember(&app);
        }
        if preferences::get().close_to_tray {
            log::info!("the window closed, the app stays in the tray");
        } else {
            log::info!("the window closed, the app quits");
            let _ = slint::quit_event_loop();
        }
        close_mail(&closing, &weak);
        slint::CloseRequestResponse::HideWindow
    });
}

fn connect_list(service: &Arc<Service>, app: &App) {
    app.on_open_link(|url| view::open_link(&url));
    let paging = service.clone();
    app.on_load_more(move || {
        let service = paging.clone();
        tokio::spawn(async move { service.view_more().await });
    });
    let (images, weak) = (service.clone(), app.as_weak());
    app.on_show_images(move || show_images(&images, &weak));
    let reloading = service.clone();
    app.on_reload(move || {
        let service = reloading.clone();
        sync::request_check();
        tokio::spawn(async move { service.view_reload().await });
    });
}

fn connect_reading(service: &Arc<Service>, app: &App) {
    let (filtering, weak) = (service.clone(), app.as_weak());
    app.on_filters_changed(move || apply_filters(&filtering, &weak, None));
    let weak = app.as_weak();
    app.on_body_moved(move || {
        if let Some(app) = weak.upgrade() {
            mail_view::place(&app);
        }
    });
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let unprotected = protection::harden_process();
    guard::start_journal();
    let commit: String = env!("BUILD_COMMIT").chars().take(COMMIT_SHOWN).collect();
    let how = if guard::is_restart() { "start again after a panic" } else { "start" };
    log::info!(
        "{how}: version {} ({commit}), {} {}",
        env!("CARGO_PKG_VERSION"),
        std::env::consts::OS,
        std::env::consts::ARCH
    );
    for what in unprotected {
        log::warn!("{what}");
    }
    guard::install();
    if !single_instance::claim() {
        return Ok(());
    }
    protection::keep_awake_in_background();
    pick_backend()?;
    #[cfg(target_os = "linux")]
    let gtk_started = gtk_loop::start();
    let runtime = tokio::runtime::Builder::new_multi_thread().worker_threads(WORKERS).enable_all().build()?;
    let _inside = runtime.enter();
    let app = App::new()?;
    look::apply_language();
    look::apply(&app);
    proton_core::timing::set_zone(&preferences::get().time_zone);
    dress(&app);
    let ended = app.as_weak();
    // No way to Proton yet: `tor_link::begin` chooses it, Tor or not, before anything goes out.
    let service = Service::undecided(PROTON_API, session::keychain(), Box::new(move |ending| auth::session_ended(&ended, ending)));
    // The account check borrows the session: a refresh would rotate the tokens of whoever saved it.
    if account_check::asked() {
        service.forbid_token_refresh();
        account_check::begin();
    }

    follow_the_view(&service, &app);

    connect_mail(&service, &app);
    actions::connect(&service, &app);
    connect_window(&service, &app);
    connect_list(&service, &app);
    search::connect(&service, &app);
    keyboard::connect(&service, &app);
    view::connect_undo(&service, &app);
    settings::connect(&service, &app);
    folder_names::connect(&service, &app);
    connect_reading(&service, &app);

    list_title(&app.as_weak(), auth::FIRST_FOLDER);
    notifications::prepare();
    guard::use_mail_store(&service);
    sync::start(&service, &app);
    auth::connect(&service, &app);
    tour::connect(&app);
    list_style::connect(&service, &app);
    incoming::listen();
    let (tor_settings, weak) = (service.clone(), app.as_weak());
    app.on_open_tor_settings(move || {
        if let Some(app) = weak.upgrade() {
            settings::open(&tor_settings, &app, "tor");
        }
    });
    tor_link::begin(&service, &app);
    app.show()?;
    modal::after_show(&app, |app| {
        window_place::restore_position(&app);
        window_place::fit_on_display(&app);
        look::taskbar_icon(&app);
        look::apply_zoom(&app);
        // The menus take the window's thread for a moment: before the envelope starts to move, not during it. The
        // event loop runs by now, which macOS wants before it takes a tray icon.
        menu::install(&app);
        tray::install(&app);
        splash::prepare(&app);
        app.invoke_begin_splash();
        // The login item starts the app in the tray: the window had to exist for what lives on it.
        if startup::started_hidden() {
            drop(app.hide());
        }
    });
    mail_picture::check::run_if_asked(&app);
    window_check::run_if_asked(&app);
    #[cfg(target_os = "linux")]
    if gtk_started {
        gtk_loop::pump();
    }
    memory::start(&app);
    view::remember_scale(&app);
    stalls::start();
    slint::run_event_loop_until_quit()?;
    guard::relaunch_if_asked();
    Ok(())
}
