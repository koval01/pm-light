//! The window as it is drawn, compared with pictures of it kept in `app/tests/screens/`. The same `.slint` files and
//! the same software renderer as the app draw each screen, with no screen attached, at fixed sizes and a clock that
//! stands still, in English. A screen that changes fails here, and its picture and the difference are written to
//! `target/screens/` to be looked at.
//!
//! Run with `UPDATE_SCREENS=1` after a change that is meant to be seen: that writes the pictures anew, which are then
//! looked at before they are committed. On macOS only: the journal's monospace face is the system's own.

#![cfg(target_os = "macos")]
#![allow(clippy::expect_used, clippy::indexing_slicing, clippy::unwrap_used, reason = "a test that cannot draw must fail")]

#[allow(clippy::all, clippy::pedantic, clippy::nursery, clippy::restriction, reason = "code generated by Slint")]
mod ui {
    slint::include_modules!();
}
use ui::*;

use image::{Rgba, RgbaImage};
use slint::{
    ComponentHandle, Model, ModelRc, SharedString, VecModel,
    platform::{
        Platform, WindowAdapter,
        software_renderer::{MinimalSoftwareWindow, PremultipliedRgbaColor, RepaintBufferType},
    },
};
use std::{cell::Cell, path::PathBuf, rc::Rc, time::Duration};

thread_local! {
    static CLOCK: Cell<Duration> = const { Cell::new(Duration::ZERO) };
}

struct Headless(Rc<MinimalSoftwareWindow>);

impl Platform for Headless {
    fn create_window_adapter(&self) -> Result<Rc<dyn WindowAdapter>, slint::PlatformError> {
        Ok(self.0.clone())
    }

    /// The clock animations run by: it moves only when a test moves it, so every picture is the same each time.
    fn duration_since_start(&self) -> Duration {
        CLOCK.get()
    }
}

/// Lets every animation finish, at a moment chosen once so that animated things stand still in the same place.
fn settle() {
    CLOCK.set(CLOCK.get() + Duration::from_secs(5));
    slint::platform::update_timers_and_animations();
}

fn draw(window: &MinimalSoftwareWindow, width: u32, height: u32) -> RgbaImage {
    window.set_size(slint::PhysicalSize::new(width, height));
    settle();
    window.request_redraw();
    let (wide, high) = (usize::try_from(width).unwrap(), usize::try_from(height).unwrap());
    let mut pixels = vec![PremultipliedRgbaColor::default(); wide * high];
    window.draw_if_needed(|renderer| {
        renderer.render(&mut pixels, wide);
    });
    let mut picture = RgbaImage::new(width, height);
    for (pixel, drawn) in picture.pixels_mut().zip(&pixels) {
        *pixel = Rgba([drawn.red, drawn.green, drawn.blue, drawn.alpha]);
    }
    picture
}

fn kept() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/screens")
}

fn written() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../target/screens")
}

/// How many pixels differ by more than a little, and a picture showing where.
fn difference(expected: &RgbaImage, actual: &RgbaImage) -> (usize, RgbaImage) {
    let mut marked = actual.clone();
    let mut differing = 0;
    for (x, y, pixel) in actual.enumerate_pixels() {
        let other = expected.get_pixel(x, y);
        let far = pixel.0.iter().zip(other.0).any(|(a, b)| a.abs_diff(b) > 24);
        if far {
            differing += 1;
            marked.put_pixel(x, y, Rgba([255, 0, 255, 255]));
        }
    }
    (differing, marked)
}

/// Compares one screen with its kept picture, or keeps it when asked to. Returns a problem, if any.
fn compare(name: &str, actual: &RgbaImage) -> Option<String> {
    let path = kept().join(format!("{name}.png"));
    if std::env::var_os("UPDATE_SCREENS").is_some() {
        std::fs::create_dir_all(kept()).unwrap();
        actual.save(&path).unwrap();
        return None;
    }
    let Ok(expected) = image::open(&path) else {
        return Some(format!("{name}: no kept picture; run with UPDATE_SCREENS=1 and look at it"));
    };
    let expected = expected.to_rgba8();
    std::fs::create_dir_all(written()).unwrap();
    if expected.dimensions() != actual.dimensions() {
        actual.save(written().join(format!("{name}.png"))).unwrap();
        return Some(format!("{name}: drawn {:?}, kept {:?}", actual.dimensions(), expected.dimensions()));
    }
    let (differing, marked) = difference(&expected, actual);
    // A few pixels of a glyph's edge may round otherwise; a moved part changes hundreds.
    if differing > 40 {
        actual.save(written().join(format!("{name}.png"))).unwrap();
        marked.save(written().join(format!("{name}.difference.png"))).unwrap();
        return Some(format!("{name}: {differing} pixels differ; see target/screens/{name}.difference.png"));
    }
    None
}

fn model<T: Clone + 'static>(items: Vec<T>) -> ModelRc<T> {
    ModelRc::from(Rc::new(VecModel::from(items)))
}

fn folders() -> ModelRc<FolderRow> {
    let system = [
        ("inbox", "Inbox", 2),
        ("starred", "Starred", 0),
        ("drafts", "Drafts", 0),
        ("scheduled", "Scheduled", 0),
        ("snoozed", "Snoozed", 0),
        ("sent", "Sent", 0),
        ("archive", "Archive", 0),
        ("spam", "Spam", 0),
        ("trash", "Trash", 0),
        ("all", "All mail", 2),
    ];
    let mut rows: Vec<FolderRow> = system
        .iter()
        .map(|(id, name, unread)| FolderRow {
            id: (*id).into(),
            name: (*name).into(),
            unread: *unread,
            active: *id == "inbox",
            section: 0,
            dot: slint::Color::default(),
            custom: false,
        })
        .collect();
    rows.push(FolderRow { id: "work".into(), name: "Work".into(), unread: 1, section: 1, custom: true, ..rows[1].clone() });
    rows.push(FolderRow {
        id: "travel".into(),
        name: "Travel".into(),
        section: 2,
        custom: true,
        dot: slint::Color::from_rgb_u8(0x2f, 0x7d, 0x5b),
        ..rows[1].clone()
    });
    model(rows)
}

fn mail_rows() -> ModelRc<MailRow> {
    let row = |id: &str, sender: &str, subject: &str, date: &str, group: i32, unread: bool, expires: i32| MailRow {
        id: id.into(),
        sender: sender.into(),
        subject: subject.into(),
        date: date.into(),
        group,
        initials: sender.chars().take(1).collect::<String>().into(),
        tint: slint::Color::from_rgb_u8(0x3b, 0x6e, 0xd6),
        age: group.max(1),
        unread,
        has_files: id == "b",
        thread: if id == "c" { 3 } else { 0 },
        expires,
        ..MailRow::default()
    };
    model(vec![
        row("a", "Ann Example", "The plan for Monday", "11:03", 1, true, -1),
        row("b", "Bob Sample", "Pictures from the trip", "09:41", 0, false, -1),
        row("c", "Carol, Dan", "Re: the report, with the corrections", "05.11", 3, false, 0),
        row("d", "Example Shop", "Your order has been sent", "04.11", 0, true, 12),
        row("e", "Newsletter", "Seven things to read this week", "02.11", 0, false, -1),
    ])
}

/// The mailbox as it stands once mail has come: the folders, a list, and the lines at the foot.
fn mailbox(app: &App) {
    app.set_ready(true);
    app.set_loading(false);
    app.set_folders(folders());
    app.set_rows(mail_rows());
    app.set_folder_title("Inbox".into());
    app.set_inbox_unread(2);
    app.set_folder_unread(2);
    app.set_updated("11:05".into());
    app.set_version_text("v0.1.0".into());
    app.set_commit_text("0000000".into());
    app.set_memory_megabytes(120);
    app.set_tor_state(2);
    app.set_tor_text("Tor · DE → NL → CH".into());
    app.set_account_initials("AE".into());
}

