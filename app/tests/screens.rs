#[test]
fn the_window_looks_as_it_did() {
    let window = MinimalSoftwareWindow::new(RepaintBufferType::NewBuffer);
    slint::platform::set_platform(Box::new(Headless(window.clone()))).expect("one platform for this test");
    let app = App::new().expect("the window");
    // English, whatever the system speaks: the pictures must not depend on the machine. Only once the window exists,
    // since its translations come with it.
    slint::select_bundled_translation("en").expect("English");
    app.show().expect("shown");
    let mut problems = Vec::new();
    let mut shoot = |name: &str, width: u32, height: u32| {
        problems.extend(compare(name, &draw(&window, width, height)));
    };

    app.set_stage(2);
    shoot("splash", 900, 580);

    mailbox(&app);
    shoot("mailbox-small", 900, 580);
    shoot("mailbox-large", 1280, 820);

    // A folder a page at a time: the pager beside the filters.
    app.set_list_pages(8);
    app.set_list_page(2);
    shoot("mailbox-pages", 900, 580);
    // One page needs no pager: the window is as without pages.
    app.set_list_pages(1);
    app.set_list_page(0);
    shoot("mailbox-small", 900, 580);
    app.set_list_page(2);
    app.set_list_pages(0);

    open_mail(&app);
    shoot("mail-small", 900, 580);
    shoot("mail-large", 1280, 820);
    app.set_list_pages(8);
    shoot("mail-pages", 900, 580);
    app.set_list_pages(0);
    app.set_list_page(0);

    app.set_account_card(AccountCard {
        name: "Ann Example".into(),
        email: "ann@example.com".into(),
        initials: "AE".into(),
        plan: "Free".into(),
        storage: "3.5 MB of 500 MB".into(),
        share: 0.2,
        loaded: true,
        can_lock: true,
    });
    app.set_account_open(true);
    shoot("account-panel", 1280, 820);
    app.set_account_open(false);

    app.set_tour_step(2);
    shoot("tour-folders", 900, 580);
    app.set_tour_step(0);

    app.set_has_mail(false);
    app.set_folder_id("trash".into());
    app.set_auto_delete(true);
    shoot("trash", 900, 580);

    app.set_asking_tor(true);
    shoot("tor-question", 900, 580);
    app.set_asking_tor(false);

    app.set_asking_list_style(true);
    shoot("list-choice-small", 900, 580);
    shoot("list-choice-large", 1280, 820);
    app.set_asking_list_style(false);

    settings_page(&app);
    shoot("settings-small", 900, 580);
    shoot("settings-large", 1280, 820);
    app.global::<Settings>().set_open(false);

    assert!(problems.is_empty(), "{problems:#?}");
    assert!(app.get_folders().row_count() > 0);
}
